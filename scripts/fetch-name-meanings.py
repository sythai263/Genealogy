#!/usr/bin/env python3
"""
fetch-name-meanings.py — bổ sung tên + ý nghĩa vào supabase/seed-name-meanings-extra.sql

Nguồn danh sách tên + giới tính: github.com/duyet/vietnamese-namedb
Nguồn ý nghĩa: tudienten.com (trang tìm kiếm /ten/{slug})

tudienten.com chặn bot bằng captcha sau ~15-20 request nhanh.
Cách chạy:
  1. Mở https://tudienten.com trên trình duyệt, giải captcha nếu có
  2. DevTools → Application → Cookies → copy giá trị `tudienten_session`
  3. TDT_COOKIE=<giá trị> python3 scripts/fetch-name-meanings.py

Không có cookie vẫn chạy được nhưng sẽ đứng chờ mỗi khi bị captcha.
Script resumable: cache HTML vào /tmp/tdt-cache/, chạy lại sẽ bỏ qua phần đã xong.
"""

import json, os, re, sys, time, unicodedata, urllib.request, http.cookiejar

REPO = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
SEED_IN = os.path.join(REPO, 'supabase/seed-name-meanings.sql')
SEED_OUT = os.path.join(REPO, 'supabase/seed-name-meanings-extra.sql')
CACHE = '/tmp/tdt-cache'
NAMEDB = 'https://raw.githubusercontent.com/duyet/vietnamese-namedb/master/{}.txt'
DELAY = float(os.environ.get('TDT_DELAY', '12'))

VN = set("abcdefghijklmnopqrstuvwxyz ABCDEFGHIJKLMNOPQRSTUVWXYZ"
    "àáạảãâầấậẩẫăằắặẳẵèéẹẻẽêềếệểễìíịỉĩòóọỏõôồốộổỗơờớợởỡ"
    "ùúụủũưừứựửữỳýỵỷỹđ"
    "ÀÁẠẢÃÂẦẤẬẨẪĂẰẮẶẲẴÈÉẸẺẼÊỀẾỆỂỄÌÍỊỈĨÒÓỌỎÕÔỒỐỘỔỖƠỜỚỢỞỠ"
    "ÙÚỤỦŨƯỪỨỰỬỮỲÝỴỶỸĐ")
BAD = ('không có nghĩa', 'không có ý nghĩa', 'chưa rõ nghĩa', 'một tên riêng')
G = [('Cả nam và nữ', 'both'), ('Nam giới', 'male'), ('Nữ giới', 'female'),
     ('Chưa xác định', 'both')]

os.makedirs(CACHE, exist_ok=True)


def slugify(name):
    s = name.lower().replace('đ', 'd')
    s = unicodedata.normalize('NFD', s)
    s = ''.join(c for c in s if unicodedata.category(c) != 'Mn')
    return '-'.join(s.split())


def fetch_url(url, cookie=''):
    req = urllib.request.Request(url, headers={
        'User-Agent': 'Mozilla/5.0 (X11; Linux x86_64) Chrome/120.0 Safari/537.36',
        'Cookie': cookie,
    })
    return urllib.request.urlopen(req, timeout=30).read().decode('utf-8')


def targets():
    out = {}
    for fname, gender, words in [
        ('boy_one_word', 'male', 1), ('girl_one_word', 'female', 1),
        ('boy', 'male', 2), ('girl', 'female', 2),
    ]:
        local = os.path.join(CACHE, f'namedb-{fname}.txt')
        if not os.path.exists(local):
            open(local, 'w', encoding='utf-8').write(fetch_url(NAMEDB.format(fname)))
        for line in open(local, encoding='utf-8'):
            n = ' '.join(line.split())
            if not n or len(n.split()) != words or not set(n) <= VN:
                continue
            out.setdefault(n.lower(), {'name': n, 'g': set()})['g'].add(gender)
    return out


def already_seeded():
    names = set()
    for p in [SEED_IN, SEED_OUT]:
        if os.path.exists(p):
            s = open(p, encoding='utf-8').read()
            names |= {m.group(1).lower() for m in re.finditer(r"\('([^']+)'", s)}
    return names


def parse_card(html, slug):
    for m in re.finditer(
        r'<h3 class="name-card-header"><a href="https://tudienten\.com/ten/([a-z0-9-]+)/\d+"[^>]*>'
        r'<span itemprop="name">([^<]+)</span></a>.*?'
        r'<p class="name-card-description"[^>]*>(.*?)</p>.*?'
        r'title="Phù hợp với giới tính: ([^"]+)"', html, re.S):
        card_slug, name, desc, gstr = m.groups()
        if card_slug != slug:
            continue
        desc = re.sub(r'<[^>]+>', '', desc)
        desc = (desc.replace('&quot;', '"').replace('&amp;', '&')
                    .replace('&#39;', "'").strip())
        gender = next((v for k, v in G if k in gstr), 'both')
        return name, gender, desc
    return None


def esc(s):
    return s.replace("'", "''")


def emit_sql(rows):
    lines = ["-- ============================================================================\n"
             "-- name_meanings extra seed — generated by scripts/fetch-name-meanings.py\n"
             "-- ============================================================================\n"
             "insert into public.name_meanings (name, gender, meaning, name_word_count, status) values\n"]
    lines += ["('%s','%s','%s',%d,'approved'),\n"
              % (esc(r['name']), r['gender'], esc(r['meaning'].rstrip('.')), len(r['name'].split()))
              for r in rows]
    if lines[-1].endswith(',\n'):
        lines[-1] = lines[-1][:-2] + ';\n'
    open(SEED_OUT, 'w', encoding='utf-8').writelines(lines)


def main():
    cookie = os.environ.get('TDT_COOKIE', '')
    if cookie and '=' not in cookie:
        cookie = f'tudienten_session={cookie}'
    todo_all = targets()
    done = already_seeded()
    todo = [v for k, v in todo_all.items() if k not in done]
    todo.sort(key=lambda x: (len(x['name'].split()), x['name'].lower()))
    print(f'targets={len(todo_all)} todo={len(todo)}')

    results = []
    for i, t in enumerate(todo):
        slug = slugify(t['name'])
        cache = os.path.join(CACHE, f'{slug}.html')
        if os.path.exists(cache):
            html = open(cache, encoding='utf-8').read()
        else:
            html = None
            for attempt in range(5):
                try:
                    html = fetch_url(f'https://tudienten.com/ten/{slug}', cookie)
                except urllib.error.HTTPError as e:
                    if e.code in (403, 404):
                        print(f'miss {t["name"]} ({e.code})')
                        break
                    print(f'err {e} — chờ {30*(attempt+1)}s')
                    time.sleep(30 * (attempt + 1))
                    continue
                if 'Xác thực' in html or 'captcha' in html.lower():
                    print('captcha — chờ 120s (hoặc đặt TDT_COOKIE)')
                    time.sleep(120)
                    continue
                break
            if html is None:
                continue
            open(cache, 'w', encoding='utf-8').write(html)
            time.sleep(DELAY)
        r = parse_card(html, slug)
        if r is None:
            continue
        name, gender, desc = r
        nb = t['g']
        if gender == 'both' and 'Cả nam và nữ' not in html:
            if nb == {'male'}:
                gender = 'male'
            elif nb == {'female'}:
                gender = 'female'
        if any(b in desc.lower() for b in BAD):
            continue
        results.append({'name': name, 'gender': gender, 'meaning': desc})
        if (i + 1) % 20 == 0:
            emit_sql(results)
            print(f'[{i+1}/{len(todo)}] saved {len(results)}')
    emit_sql(results)
    print(f'DONE {len(results)} → {SEED_OUT}')


if __name__ == '__main__':
    main()
